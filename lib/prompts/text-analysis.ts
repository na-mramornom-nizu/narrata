export function textDistributionContext(distributionFinding: unknown) {
  return (
    ' Проверенное распределение: ' +
    JSON.stringify(distributionFinding) +
    ('. Сформулируй конкретный вывод по этим фактам: называй сами объекты или статусы, естественно согласуя слова. Не пиши «самые ' +
      'крупные группы», «равные доли категорий» или «одна группа». При равенстве назови обе сравниваемые категории. В абзаце объясни ' +
      'вывод исходными долями, затем добавь другой подтверждающий факт из отчёта.')
  );
}

