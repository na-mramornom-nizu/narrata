export function clarificationPlanError(question: string) {
  return (
    'Проверь самостоятельный вопрос ещё раз: ' +
    question +
    '. Если нужных полей нет, верни unsupported. Если они есть, выбери точные колонки и значения из records. Не теряй запрошенные поля.'
  );
}

export function repairTablePlan(
  originalQuestion: string | undefined,
  question: string,
  reason: string
) {
  return (
    'Исходный вопрос пользователя: ' +
    originalQuestion +
    '\nВопрос с раскрытым контекстом: ' +
    question +
    '\nИсправь JSON-план. Ошибка валидации: ' +
    reason
  );
}

